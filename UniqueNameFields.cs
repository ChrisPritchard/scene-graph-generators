namespace Generators;

using System.Collections.Immutable;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

[Generator]
public class UniqueNameFields : IIncrementalGenerator
{
    const string NAMESPACE = "Generators";
    const string ATTRIBUTE = "SceneGraphAttribute";
    const string ATTRIBUTE_SOURCE = "namespace " + NAMESPACE + @";

[System.AttributeUsage(AttributeTargets.Class, Inherited = false)]
public sealed class " + ATTRIBUTE + @"(string sceneName) : System.Attribute
{
    public string SceneName { get; } = sceneName;
}";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(ctx => ctx.AddSource($"{ATTRIBUTE}.Generated.cs", SourceText.From(ATTRIBUTE_SOURCE, Encoding.UTF8)));

        

        var sceneFiles = context.AdditionalTextsProvider.Where(static t => t.Path.EndsWith(".tscn"))
            .Select(static (t, ct) => (Path.GetFileNameWithoutExtension(t.Path), t.GetText(ct)?.ToString() ?? ""))
            .Collect()
            .Select((arr, _) => arr.ToImmutableDictionary(x => x.Item1, x => x.Item2));

        var classes = context.SyntaxProvider
            .ForAttributeWithMetadataName($"{NAMESPACE}.{ATTRIBUTE}",
                static (obj, _) => obj is ClassDeclarationSyntax,
                static (ctx, _) =>
                {
                    var classSymbol = (INamedTypeSymbol)ctx.TargetSymbol;
                    var attr = ctx.Attributes[0];
                    return (
                        classSymbol.ContainingNamespace.IsGlobalNamespace ? null : classSymbol.ContainingNamespace.ToDisplayString(), 
                        classSymbol.Name, 
                        attr.ConstructorArguments[0].Value as string ?? "");
                })
                .Collect();

        var combined = sceneFiles.Combine(classes);

        context.RegisterSourceOutput(combined, static (spc, pair) => Emit(pair.Left, pair.Right, spc));
    }


    private static void Emit(
        ImmutableDictionary<string, string> sceneFiles,
        ImmutableArray<(string Namespace, string ClassName, string ScenePath)> classes, 
        SourceProductionContext spc)
    {
        if (classes.IsDefaultOrEmpty)
            return;

        foreach(var classInfo in classes)
        {
            if(!sceneFiles.TryGetValue(classInfo.ScenePath, out string SceneText))
            {
                var allScenes = "";
                foreach(var k in sceneFiles.Keys)
                    allScenes += k + "\n";
                spc.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "SG001", "Scene not found",
                        $"Could not find AdditionalFile matching '{classInfo.ScenePath}'. " +
                        "Ensure the .tscn is marked as a C# analyzer additional file." + allScenes,
                        "SceneGraph", DiagnosticSeverity.Warning, true),
                    Location.None));
                return;
            }
            
            var nodes = ParseUniqueNodes(SceneText);
            if(nodes.Count == 0)
                continue;

            spc.AddSource($"{classInfo.ClassName}.SceneGraph.g.cs", GeneratePartialClass(classInfo, nodes));
        }
    }

    private static string GeneratePartialClass((string Namespace, string ClassName, string ScenePath) classInfo, List<(string Name, string Type)> uniqueNodes)
    {
        var sb = new StringBuilder();
        sb.AppendLine(@"// <auto-generated/>");
        if (!string.IsNullOrWhiteSpace(classInfo.Namespace))
        {
            sb.AppendLine($"namespace {classInfo.Namespace};");
            sb.AppendLine();
        }

        sb.AppendLine($"public partial class {classInfo.ClassName}");
        sb.AppendLine("{");

        foreach (var uniqueNode in uniqueNodes)
        {
            var fieldName = ToLowerCamelCase(uniqueNode.Name);

            sb.AppendLine($"    private {uniqueNode.Type} _{fieldName};");
            sb.AppendLine();
            sb.AppendLine($"    private {uniqueNode.Type} {fieldName}");
            sb.AppendLine($"    {{");
            sb.AppendLine($"        get => _{fieldName} ??= GetNode<{uniqueNode.Type}>(\"%{uniqueNode.Name}\");");
            sb.AppendLine($"    }}");
            sb.AppendLine();
        }
        sb.AppendLine("}");
        return sb.ToString().Replace("\r\n", "\n");
    }

    private static string ToLowerCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name) || name.Length < 2)
            return name.ToLowerInvariant();

        if (char.IsUpper(name[0]))
            return char.ToLowerInvariant(name[0]) + name.Substring(1);

        return name;
    }

    private static List<(string Name, string Type)> ParseUniqueNodes(string tscn)
    {
        var results = new List<(string, string)>();
        var lines = tscn.Split('\n');

        string pendingName = null;
        string pendingType = null;
        bool isUnique = false;

        static Dictionary<string, string> parseLine(string line) => 
            line.Split("[ ]".ToCharArray(), StringSplitOptions.RemoveEmptyEntries)
                .Select(s => s.Split('='))
                .Where(a => a.Length == 2)
                .ToDictionary(a => a[0], a=> a[1].Replace("\"", ""));
            
        Dictionary<string, string> customTypes = [];

        foreach (var raw in lines)
        {
            var line = raw.TrimEnd('\r');

            if (line.StartsWith("["))
            {
                if(pendingName != null && isUnique)
                    results.Add((pendingName, pendingType));

                pendingName = null;
                pendingType = null;
                isUnique = false;
            }

            if(line.StartsWith("[ext_resource type=\"Script\" "))
            {
                var parts = parseLine(line);
                customTypes.Add(parts["id"], Path.GetFileNameWithoutExtension(parts["path"]));
                continue;
            }

            if(line.StartsWith("[node "))
            {
                var parts = parseLine(line);
                pendingName = parts["name"];
                pendingType = parts["type"];
                continue;
            }

            if (pendingName != null && line.Contains("unique_name_in_owner = true"))
            {
                isUnique = true;
                continue;
            }

            if(pendingName != null && line.StartsWith("script = ExtResource(\""))
            {
                pendingType = customTypes[line.Substring(22, 7)];
                continue;
            }
        }

        if(pendingName != null && isUnique)
            results.Add((pendingName, pendingType));

        return results;
    }
}